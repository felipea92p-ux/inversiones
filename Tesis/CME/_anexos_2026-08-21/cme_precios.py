# Etiquetas: indice 0 = dic-2008; indice 1 = ene-2009 ... salvo el ultimo (21-ago-2026, parcial)
def etiqueta(i):
    if i == 0: return "2008-12"
    m = (i - 1) % 12 + 1
    y = 2009 + (i - 1) // 12
    return f"{y}-{m:02d}"

